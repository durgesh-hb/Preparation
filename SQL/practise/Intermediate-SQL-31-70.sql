-- P36 Calculate total order value for every customer.
select c.customer_name, sum(o.total_amount)
from customers c
join orders o
on c.customer_id = o.customer_id
group by c.customer_name;

-- P37 Find customers whose total order value exceeds 10,000.
select c.customer_name, sum(o.total_amount) as total
from customers c
join orders o 
on c.customer_id = o.customer_id
group by c.customer_name
having total > 10000;

-- P38 Find the average order amount for each customer.
select c.customer_name, avg(o.total_amount)
from customers c
join orders o
on c.customer_id = o.customer_id
group by c.customer_name;

